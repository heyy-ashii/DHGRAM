// Compiles supabase/migrations/*.sql into a JS module so the SQL travels with
// the serverless function no matter how Vercel resolves includeFiles.
//
//   node server/scripts/build-migrations.js   (chained from `npm run build`)
//
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const dir = join(root, 'supabase/migrations');
const out = join(root, 'server/supabase/migrations.generated.js');

const files = (await readdir(dir)).filter((f) => f.endsWith('.sql')).sort();
const entries = [];
for (const name of files) {
  const sql = await readFile(join(dir, name), 'utf8');
  entries.push(`  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`);
}

const contents =
  '// Generated by server/scripts/build-migrations.js — do not edit.\n' +
  `export const MIGRATIONS = [\n${entries.join('\n')}\n];\n`;
await writeFile(out, contents);
console.info(`[build] compiled ${files.length} migrations -> server/supabase/migrations.generated.js`);
